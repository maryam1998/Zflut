final Map<String, VocabTopic> _byCategory = {
  for (final t in kVocabTopics)
    for (final c in t.categories) c: t,
};

/// موضوعِ اصلیِ یک دسته‌ی ریز (null = ناشناخته)
VocabTopic? vocabTopicOfCategory(String category) => _byCategory[category];

VocabTopic? vocabTopicByKey(String? key) {
  if (key == null) return null;
  for (final t in kVocabTopics) {
    if (t.key == key) return t;
  }
  return null;
}
